// Command acpgen generates the pinned stable ACP wire model.
package main

import (
	"bytes"
	"crypto/sha1"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"unicode"
)

type node map[string]any

var defs map[string]node
var out bytes.Buffer
var roots = strings.Fields("InitializeRequest InitializeResponse NewSessionRequest NewSessionResponse PromptRequest PromptResponse CancelNotification SessionNotification RequestPermissionRequest RequestPermissionResponse")

func keys[V any](m map[string]V) []string {
	a := make([]string, 0, len(m))
	for k := range m {
		a = append(a, k)
	}
	sort.Strings(a)
	return a
}
func obj(v any) node {
	if v == nil {
		return node{}
	}
	return node(v.(map[string]any))
}
func list(v any) []any {
	if v == nil {
		return nil
	}
	return v.([]any)
}
func name(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })
	for i, p := range parts {
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	s = strings.Join(parts, "")
	if s == "" {
		return "Variant"
	}
	if s == "Meta" {
		return "Meta"
	}
	return s
}
func ref(n node) string { s, _ := n["$ref"].(string); return strings.TrimPrefix(s, "#/$defs/") }
func typ(n node) string {
	if r := ref(n); r != "" {
		return r
	}
	if a := list(n["allOf"]); len(a) == 1 {
		return typ(obj(a[0]))
	}
	t := n["type"]
	if a, ok := t.([]any); ok {
		for _, v := range a {
			if v != "null" {
				t = v
				break
			}
		}
	}
	switch t {
	case "string":
		return "string"
	case "integer":
		if n["format"] == "uint64" {
			return "uint64"
		}
		if n["format"] == "uint16" {
			return "uint16"
		}
		return "int64"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		return "[]" + typ(obj(n["items"]))
	}
	if a := list(n["anyOf"]); len(a) == 2 {
		for _, v := range a {
			q := obj(v)
			if q["type"] != "null" {
				return typ(q)
			}
		}
	}
	return "json.RawMessage"
}
func flatten(n node) node {
	p := map[string]any{}
	r := []any{}
	for _, v := range list(n["allOf"]) {
		q := obj(v)
		if x := ref(q); x != "" {
			q = defs[x]
		}
		q = flatten(q)
		for k, v := range obj(q["properties"]) {
			p[k] = v
		}
		r = append(r, list(q["required"])...)
	}
	for k, v := range obj(n["properties"]) {
		p[k] = v
	}
	r = append(r, list(n["required"])...)
	z := node{}
	for k, v := range n {
		z[k] = v
	}
	z["properties"] = p
	z["required"] = r
	return z
}
func emitStruct(nm string, n node, definition string) {
	n = flatten(n)
	fmt.Fprintf(&out, "type %s struct {\n", nm)
	req := map[string]bool{}
	for _, v := range list(n["required"]) {
		req[v.(string)] = true
	}
	p := obj(n["properties"])
	for _, k := range keys(p) {
		t := typ(obj(p[k]))
		if !req[k] {
			t = "Optional[" + t + "]"
		}
		fmt.Fprintf(&out, "%s %s `json:%q`\n", name(k), t, k)
	}
	fmt.Fprintln(&out, "Extra map[string]json.RawMessage `json:\"-\"`\n}")
	fmt.Fprintf(&out, "func (v %s) MarshalJSON() ([]byte,error) { return marshalObject(%q,v) }\nfunc (v *%s) UnmarshalJSON(b []byte) error { type plain %s; var p plain; if err:=unmarshalObject(%q,b,&p);err!=nil{return err};*v=%s(p);return nil }\n", nm, definition, nm, nm, definition, nm)
}
func branches(n node) []any {
	if a := list(n["oneOf"]); len(a) > 0 {
		return a
	}
	return list(n["anyOf"])
}
func stringUnion(n node) bool {
	a := branches(n)
	if len(a) == 0 {
		return false
	}
	for _, v := range a {
		if obj(v)["type"] != "string" {
			return false
		}
	}
	return true
}
func generate(schema []byte) ([]byte, error) {
	var doc node
	if err := json.Unmarshal(schema, &doc); err != nil {
		return nil, err
	}
	defs = map[string]node{}
	for k, v := range obj(doc["$defs"]) {
		defs[k] = obj(v)
	}
	seen := map[string]bool{}
	var walk func(any)
	walk = func(v any) {
		switch x := v.(type) {
		case map[string]any:
			if r := ref(node(x)); r != "" && !seen[r] {
				seen[r] = true
				walk(map[string]any(defs[r]))
			}
			for _, v := range x {
				walk(v)
			}
		case []any:
			for _, v := range x {
				walk(v)
			}
		}
	}
	for _, r := range roots {
		seen[r] = true
		walk(map[string]any(defs[r]))
	}
	if len(seen) != 108 {
		return nil, fmt.Errorf("closure: got %d definitions, want 108", len(seen))
	}
	out.Reset()
	fmt.Fprintln(&out, "// Code generated by acpgen; DO NOT EDIT.\n// Source: agentclientprotocol/agent-client-protocol@e2d83349bc9e28a4059ea3acefa1c91c966f74e2\n// schema/v1/schema.json blob d6f7731bf74b3dbe3b9bbda52957a7637a12e688\npackage protocol\n\nimport \"encoding/json\"")
	for _, nm := range keys(seen) {
		n := defs[nm]
		a := branches(n)
		if len(a) > 0 && !stringUnion(n) {
			fmt.Fprintf(&out, "// %s holds one of its concrete variant types in Value.\ntype %s struct { Value any }\n", nm, nm)
			variants := []string{}
			for i, v := range a {
				q := obj(v)
				suffix, _ := q["title"].(string)
				for _, pk := range keys(obj(q["properties"])) {
					pv := obj(q["properties"])[pk]
					if c, ok := obj(pv)["const"].(string); ok {
						suffix = c
					}
				}
				if suffix == "" {
					if x := list(q["allOf"]); len(x) == 1 {
						suffix = ref(obj(x[0]))
					}
				}
				if suffix == "" {
					suffix = fmt.Sprintf("Variant%d", i+1)
				}
				vn := nm + name(suffix) + "Variant"
				variants = append(variants, vn)
				if q["type"] == "array" {
					fmt.Fprintf(&out, "type %s %s\n", vn, typ(q))
					emitScalar(vn, fmt.Sprintf("%s/%d", nm, i))
				} else {
					merged := flatten(q)
					p := obj(merged["properties"])
					for k, v := range obj(n["properties"]) {
						p[k] = v
					}
					merged["required"] = append(list(merged["required"]), list(n["required"])...)
					emitStruct(vn, merged, fmt.Sprintf("%s/%d", nm, i))
				}
			}
			fmt.Fprintf(&out, "func (v %s) MarshalJSON() ([]byte,error) { switch v.Value.(type) {", nm)
			for _, vn := range variants {
				fmt.Fprintf(&out, "case %s,*%s:", vn, vn)
				fmt.Fprintf(&out, "return marshalUnion(%q,v.Value);", nm)
			}
			fmt.Fprintln(&out, "};return nil,errVariant }")
			fmt.Fprintf(&out, "func (v *%s) UnmarshalJSON(b []byte) error { i,err:=selectVariant(%q,b);if err!=nil{return err};switch i {", nm, nm)
			for i, vn := range variants {
				fmt.Fprintf(&out, "case %d: var p %s;if err:=json.Unmarshal(b,&p);err!=nil{return err};v.Value=p;", i, vn)
			}
			fmt.Fprintln(&out, "};return nil }")
		} else if n["type"] == "object" {
			emitStruct(nm, n, nm)
		} else {
			t := typ(n)
			if stringUnion(n) || n["enum"] != nil {
				t = "string"
			}
			fmt.Fprintf(&out, "type %s %s\n", nm, t)
			emitScalar(nm, nm)
			values := map[string]bool{}
			for _, v := range list(n["enum"]) {
				if s, ok := v.(string); ok {
					values[s] = true
				}
			}
			if stringUnion(n) {
				for _, v := range branches(n) {
					if s, ok := obj(v)["const"].(string); ok {
						values[s] = true
					}
				}
			}
			for _, v := range keys(values) {
				fmt.Fprintf(&out, "const %s%s %s = %q\n", nm, name(v), nm, v)
			}
		}
	}
	fmt.Fprintln(&out, "var supportedDefinitions = definitionSet([]string{")
	for _, nm := range keys(seen) {
		fmt.Fprintf(&out, "%q,\n", nm)
	}
	fmt.Fprintln(&out, "})")
	return format.Source(out.Bytes())
}
func emitScalar(nm, definition string) {
	fmt.Fprintf(&out, "func (v %s) MarshalJSON() ([]byte,error) { type plain %s; b,err:=json.Marshal(plain(v));if err!=nil{return nil,err};if err=ValidateJSON(%q,b);err!=nil{return nil,err};return b,nil }\n", nm, nm, definition)
	fmt.Fprintf(&out, "func (v *%s) UnmarshalJSON(b []byte) error {if err:=ValidateJSON(%q,b);err!=nil{return err};type plain %s; var p plain;if err:=unmarshalExact(b,&p);err!=nil{return err};*v=%s(p);return nil }\n", nm, definition, nm, nm)
}
func checkBlob(b []byte, want string) error {
	h := sha1.New()
	_, _ = fmt.Fprintf(h, "blob %d\x00", len(b))
	_, _ = h.Write(b)
	if got := hex.EncodeToString(h.Sum(nil)); got != want {
		return fmt.Errorf("source pin mismatch: got %s want %s", got, want)
	}
	return nil
}
func main() {
	meta, err := os.ReadFile("meta.json")
	if err != nil {
		panic(err)
	}
	if err = checkBlob(meta, "b9c67caa417dd2285a31d07309a215a6110bbfaf"); err != nil {
		panic(err)
	}
	b, err := os.ReadFile("schema.json")
	if err != nil {
		panic(err)
	}
	if err = checkBlob(b, "d6f7731bf74b3dbe3b9bbda52957a7637a12e688"); err != nil {
		panic(err)
	}
	b, err = generate(b)
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("types_gen.go", b, 0644); err != nil {
		panic(err)
	}
}
